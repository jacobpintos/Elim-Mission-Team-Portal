/**
 * What Miriam can do on her own, without Claude, and the requests she learned
 * each from: a request is hers when it means what one of these examples
 * means (./understand), however it is worded. `other` is everything that
 * isn't hers — the things Claude does — so that she knows it when she sees it
 * and hands it on.
 *
 * An event's name is in braces: it is read as "the event", as the names in a
 * request are (./events: masked), so that what is asked decides, not which
 * event — "where's {the picnic}" is nearer "where is {Youth Night}" than
 * "who's going to {the picnic}".
 *
 * She learns more as she goes: each request Claude handles is kept as one
 * more example of what it was (./learn), so the next one worded like it is
 * hers. These are where she starts. Their meanings are worked out ahead of
 * time (models/minilm/seedVectors.json, by scripts/miriam-model/seeds.js);
 * a test checks they are up to date.
 */

